// =========================================================================
// debounce.js (連続発火を防ぐデバウンス処理のユーティリティモジュール)
// =========================================================================
// 役割：リサイズイベントなど、短時間に大量発生する処理を間引いて
// パフォーマンスの低下を防ぐ。
// =========================================================================

/**
 * デバウンス関数
 * 連続してイベントが発生した際、指定した時間（wait）だけ処理を遅延させ、
 * その間に次のイベントが発生しなかった時に初めて関数を実行する。
 *
 * @param {Function} func - 実行したい関数
 * @param {number} [wait=200] - 待機時間（ミリ秒）。デフォルトは200ms
 * @returns {Function} デバウンス化された実行用関数
 */
export const debounce = (func, wait = 200) => {
  let timer;
  return (...args) => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      func(...args);
    }, wait);
  };
};