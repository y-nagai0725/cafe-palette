/**
 * 指定した時間（ミリ秒）だけ待機する関数
 * @param {number} ms - 待機する時間（ミリ秒）
 * @returns {Promise<void>} 指定時間経過後に解決されるPromise
 */
export const waitTime = (ms) => {
  return new Promise((resolve) => {
    setTimeout(resolve, ms);
  });
};